// Builds the two tables that say where a place is, for the sun's position
// (public/assets/sun.js):
//
//   public/assets/zone-coords.js   IANA zone → [latitude, longitude]
//   src/data/airport-coords.json   airport and city codes → the same, packed
//
// Zones: the time zone database's own zone.tab and zone1970.tab give each
// zone's principal location, by its rules the most populous city in the zone.
// Old names (US/Pacific, Asia/Calcutta) take the coordinates of the zone the
// `backward` file links them to, or names as the place they meant. Source: https://data.iana.org/time-zones/tzdb/
//
// Airports and city codes: latitude and longitude from lxndrblz/Airports
// (airports.csv and citycodes.csv), for every code already in
// src/data/airport-map-data.json. This script doesn't change that file. A city
// code with no row of its own gets the mean of its airports.
//
// Coordinates are rounded to 0.1°, about 11 km: the sun moves that far in 24
// seconds.
//
// Run with: node scripts/build-coords.mjs
import { readFileSync, writeFileSync } from "node:fs";

const TZDB = "https://data.iana.org/time-zones/tzdb/";
const AIRPORTS = "https://raw.githubusercontent.com/lxndrblz/Airports/refs/heads/main/";

async function text(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return response.text();
}

const round = (degrees) => Math.round(degrees * 10) / 10;

// "+404251-0740023" (±DDMM[SS]±DDDMM[SS]) → [40.7, -74]
function readIso6709(value) {
  const m = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(value);
  if (!m) throw new Error(`Can't read the coordinates "${value}"`);
  const degrees = (sign, d, min, s) =>
    (sign === "-" ? -1 : 1) * (+d + +min / 60 + +(s ?? 0) / 3600);
  return [round(degrees(m[1], m[2], m[3], m[4])), round(degrees(m[5], m[6], m[7], m[8]))];
}

// --- Zones ---

const [zoneTab, zone1970Tab, backward] = await Promise.all(
  ["zone.tab", "zone1970.tab", "backward"].map((name) => text(TZDB + name)),
);
const zones = {};
// zone1970.tab first, then zone.tab over it: where both list a zone they agree
for (const table of [zone1970Tab, zoneTab]) {
  for (const line of table.split("\n")) {
    if (!line || line.startsWith("#")) continue;
    const [, coordinates, name] = line.split("\t");
    zones[name] = readIso6709(coordinates);
  }
}
// An old name is linked to the zone that keeps the same clock, which can be
// far away: Iceland is linked to Africa/Abidjan. Where the file names the
// place the old name meant ("#= Atlantic/Reykjavik"), that's the one to use.
const links = {};
for (const line of backward.split("\n")) {
  const m = /^Link\s+(\S+)\s+(\S+)(?:\s+#=\s+(\S+))?/.exec(line);
  if (m) links[m[2]] = m[3] ?? m[1];
}
// Old names whose link is to another latitude, and that the file doesn't
// place: set by hand
const OLD_PLACES = {
  "Africa/Timbuktu": [16.8, -3],
  "America/Coral_Harbour": [64.1, -83.2],
  "Antarctica/South_Pole": [-90, 0],
  "Atlantic/Jan_Mayen": [70.9, -8.7],
  "Pacific/Yap": [9.5, 138.1],
};
Object.assign(zones, OLD_PLACES);
let linked = 0;
for (const name of Object.keys(links)) {
  if (zones[name]) continue;
  let target = links[name];
  for (let i = 0; i < 5 && !zones[target] && links[target]; i++) target = links[target];
  if (zones[target]) {
    zones[name] = zones[target];
    linked++;
  }
}
const sortedZones = Object.fromEntries(Object.entries(zones).sort(([a], [b]) => (a < b ? -1 : 1)));
writeFileSync(
  new URL("../public/assets/zone-coords.js", import.meta.url),
  "// Each time zone's principal place, as [latitude, longitude] to 0.1°.\n" +
    "// Generated by scripts/build-coords.mjs from the time zone database's\n" +
    "// zone.tab, zone1970.tab and backward; don't edit.\n" +
    `export default ${JSON.stringify(sortedZones)};\n`,
);

const missing = Intl.supportedValuesOf("timeZone").filter((name) => !zones[name]);
console.log(`Zones: ${Object.keys(zones).length} (${linked} old names)`);
console.log(`Zones this runtime knows that have no place: ${missing.join(", ") || "none"}`);

// --- Airports and city codes ---

function parseCsv(csv) {
  const rows = csv
    .trim()
    .split("\n")
    .map((line) => {
      const fields = [];
      let field = "";
      let quoted = false;
      for (let i = 0; i < line.length; i++) {
        const c = line[i];
        if (c === '"') {
          if (quoted && line[i + 1] === '"') {
            field += '"';
            i++;
          } else quoted = !quoted;
        } else if (c === "," && !quoted) {
          fields.push(field.trim());
          field = "";
        } else field += c;
      }
      fields.push(field.trim());
      return fields;
    });
  const header = rows.shift();
  return rows.map((fields) => Object.fromEntries(header.map((h, i) => [h, fields[i] ?? ""])));
}

const [airportsCsv, cityCsv] = await Promise.all(
  ["airports.csv", "citycodes.csv"].map((name) => text(AIRPORTS + name)),
);
const known = JSON.parse(
  readFileSync(new URL("../src/data/airport-map-data.json", import.meta.url), "utf8"),
);
const at = {};
const members = {};
const place = (row) => {
  const lat = Number(row.latitude);
  const lon = Number(row.longitude);
  return row.latitude && row.longitude && Number.isFinite(lat) && Number.isFinite(lon)
    ? [lat, lon]
    : null;
};
for (const row of parseCsv(airportsCsv)) {
  const where = place(row);
  if (!where) continue;
  at[row.code] ??= where;
  if (row.city_code && row.city_code !== row.code) {
    members[row.city_code] ??= [];
    members[row.city_code].push(where);
  }
}
const cityRows = {};
for (const row of parseCsv(cityCsv)) {
  const where = place(row);
  if (where) cityRows[row.code] = where;
}
// The same order the zone map is built in: a city's own row wins, then the
// airport with that code, then the mean of the city's airports
const mean = (list) => [0, 1].map((i) => list.reduce((sum, p) => sum + p[i], 0) / list.length);
const DIGITS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_";
let records = "";
let without = 0;
for (const code of Object.keys(known).sort((a, b) => (a < b ? -1 : 1))) {
  const where = cityRows[code] ?? at[code] ?? (members[code] ? mean(members[code]) : null);
  if (!where || !/^[A-Z0-9]{3}$/.test(code)) {
    without++;
    continue;
  }
  // Tenths of a degree from the south pole and from 180° west, as one number
  // in four base-64 digits
  let n = Math.round((where[0] + 90) * 10) * 3601 + Math.round((where[1] + 180) * 10);
  let digits = "";
  for (let i = 0; i < 4; i++) {
    digits = DIGITS[n % 64] + digits;
    n = Math.floor(n / 64);
  }
  records += code + digits;
}
writeFileSync(
  new URL("../src/data/airport-coords.json", import.meta.url),
  `${JSON.stringify({
    about:
      "Airport and city codes with their coordinates, from lxndrblz/Airports. Generated by scripts/build-coords.mjs; read by src/lib/coords.js.",
    records,
  })}\n`,
);
console.log(`Airport and city codes: ${records.length / 7} with a place, ${without} without`);
